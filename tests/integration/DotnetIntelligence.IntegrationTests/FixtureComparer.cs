using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

namespace DotnetIntelligence.IntegrationTests;

/// <summary>Compares one generation with one run of expected.yml; returns readable differences.</summary>
internal static partial class FixtureComparer
{
    public static IReadOnlyList<string> Compare(JsonObject expected, int exitCode, string output, string stderr)
    {
        var failures = new List<string>();
        if ((string?)expected["exitCode"] is { } code && int.Parse(code) != exitCode)
        {
            failures.Add($"exit code {exitCode}, expected {code}. stderr: {stderr.Trim()}");
        }
        if (!File.Exists(Path.Combine(output, "manifest.json")))
        {
            failures.Add("no manifest was written");
            return failures;
        }
        var manifest = JsonNode.Parse(File.ReadAllText(Path.Combine(output, "manifest.json")))!;
        Check(failures, "status", (string?)expected["status"], (string?)manifest["status"]);

        var projects = Read(output, "graph/projects.ndjson");
        var evidence = Read(output, "graph/evidence.ndjson").ToDictionary(e => (string)e["id"]!, StringComparer.Ordinal);
        string At(string evidenceId) => evidence.TryGetValue(evidenceId, out var e) ? $"{e["path"]}:{e["span"]!["startLine"]}" : "?";
        IEnumerable<string> Lines(JsonObject record) => record["evidence"]!.AsArray().Select(e => At((string)e!)).Distinct().Order(StringComparer.Ordinal);

        if (expected["loadModes"] is JsonObject loadModes)
        {
            var actual = projects.Where(p => (string?)p["recordType"] == "analysisContext").Select(p => $"{p["project"]}={p["loadMode"]}");
            CompareSets(failures, "load modes", loadModes.Select(p => $"{p.Key}={p.Value}"), actual);
        }

        if (expected["projects"] is JsonObject expectedProjects)
        {
            foreach (var (path, fields) in expectedProjects)
            {
                var record = projects.FirstOrDefault(p => (string?)p["recordType"] == "project" && (string?)p["path"] == path);
                if (record is null)
                {
                    failures.Add($"missing project record {path}");
                    continue;
                }
                foreach (var (field, value) in fields!.AsObject())
                {
                    var expectedText = Text(value);
                    var actualText = Text(record[field]);
                    if (expectedText != actualText)
                    {
                        failures.Add($"project {path}: {field} '{actualText}', expected '{expectedText}'");
                    }
                }
            }
        }

        var diagnostics = Read(output, "graph/diagnostics.ndjson");
        var expectedDiagnostics = (expected["diagnostics"]?.AsArray() ?? []).Select(d => $"{d!["code"]}@{d["scope"]}").ToList();
        var actualDiagnostics = diagnostics.Select(d => (Key: $"{d["code"]}@{d["scope"]}", Severity: (string)d["severity"]!)).ToList();
        foreach (var missing in expectedDiagnostics.Except(actualDiagnostics.Select(d => d.Key)))
        {
            failures.Add($"missing diagnostic {missing}");
        }
        foreach (var extra in actualDiagnostics.Where(d => d.Severity != "info").Select(d => d.Key).Except(expectedDiagnostics))
        {
            failures.Add($"unexpected diagnostic {extra}: {diagnostics.First(d => $"{d["code"]}@{d["scope"]}" == extra)["message"]}");
        }

        var entities = Read(output, "graph/entities.ndjson").Select(e => (string)e["id"]!).ToHashSet(StringComparer.Ordinal);
        foreach (var absent in expected["absentEntities"]?.AsArray().Select(a => Id((string)a!)) ?? [])
        {
            if (entities.Contains(absent))
            {
                failures.Add($"entity {absent} should not exist");
            }
        }
        foreach (var present in expected["entities"]?.AsArray().Select(a => Id((string)a!)) ?? [])
        {
            if (!entities.Contains(present))
            {
                failures.Add($"missing entity {present}");
            }
        }

        var declarations = Read(output, "graph/declarations.ndjson");
        foreach (var item in expected["declarations"]?.AsArray().Select(d => d!.AsObject()) ?? [])
        {
            var entity = Id((string)item["entity"]!);
            var actual = declarations.Where(d => (string)d["entity"]! == entity)
                .Select(d => d["generator"] is { } g ? $"generated by {g}" : $"{d["path"]}:{d["span"]!["startLine"]}");
            CompareSets(failures, $"declarations of {entity}", item["at"]!.AsArray().Select(a => (string)a!), actual);
        }

        var relations = Read(output, "graph/relations.ndjson");
        foreach (var group in expected["relations"]?.AsArray().Select(g => g!.AsObject()) ?? [])
        {
            var kinds = group["kinds"]!.AsArray().Select(k => (string)k!).ToHashSet(StringComparer.Ordinal);
            var fromPrefix = group["from"] is { } f ? Id((string)f!) : "dotnet:";
            var toPrefix = group["to"] is { } t ? Id((string)t!) : "dotnet:";
            var withLines = group["items"]!.AsArray().Any(i => ((string)i!).Contains(" @", StringComparison.Ordinal));
            var expectedItems = group["items"]!.AsArray().Select(i => Relation((string)i!, withLines));
            var actual = relations.Where(r => kinds.Contains((string)r["kind"]!) && ((string)r["from"]!).StartsWith(fromPrefix, StringComparison.Ordinal)
                    && ((string)r["to"]!).StartsWith(toPrefix, StringComparison.Ordinal))
                .Select(r => $"{r["kind"]} {r["from"]} -> {r["to"]}{(r["usage"] is { } u ? $" usage={u}" : string.Empty)}{(withLines ? " @" + string.Join(",", Lines(r)) : string.Empty)}");
            CompareSets(failures, $"relations {string.Join("/", kinds)}", expectedItems, actual);
        }

        var observations = Read(output, "graph/observations.ndjson");
        if (expected["observations"] is JsonObject expectedObservations)
        {
            var kinds = expectedObservations["kinds"]!.AsArray().Select(k => (string)k!).ToHashSet(StringComparer.Ordinal);
            var remaining = observations.Where(o => kinds.Contains((string)o["kind"]!)).ToList();
            foreach (var item in expectedObservations["items"]!.AsArray().Select(i => i!.AsObject()))
            {
                var match = remaining.FirstOrDefault(o => Matches(item, o, Lines(o).ToList()));
                if (match is null)
                {
                    failures.Add($"missing observation {item.ToJsonString()}");
                }
                else
                {
                    remaining.Remove(match);
                }
            }
            foreach (var extra in remaining)
            {
                failures.Add($"unexpected observation {extra["kind"]} @{string.Join(",", Lines(extra))}: {Describe(extra)}");
            }
        }

        if (expected["links"] is JsonArray expectedLinks)
        {
            var byId = observations.ToDictionary(o => (string)o["id"]!, StringComparer.Ordinal);
            string Side(JsonNode? side) => side is null ? "null" : byId.TryGetValue((string)side["observation"]!, out var o) ? Lines(o).First() : "?";
            var actual = Read(output, "graph/links.ndjson").Select(l => $"{l["via"]} {l["kind"]} {l["resolution"]} {Side(l["from"])} -> {Side(l["to"])}");
            CompareSets(failures, "links", expectedLinks.Select(l => (string)l!), actual);
        }

        // G4.1: every link keeps the evidence of both sides (5.1).
        var observationsById = observations.ToDictionary(o => (string)o["id"]!, StringComparer.Ordinal);
        foreach (var link in Read(output, "graph/links.ndjson"))
        {
            var linkEvidence = link["evidence"]!.AsArray().Select(e => (string)e!).ToHashSet(StringComparer.Ordinal);
            foreach (var side in new[] { link["from"], link["to"] }.OfType<JsonObject>())
            {
                if (!observationsById.TryGetValue((string)side["observation"]!, out var observation))
                {
                    continue;
                }
                var missing = observation["evidence"]!.AsArray().Select(e => (string)e!).Where(e => !linkEvidence.Contains(e)).ToList();
                if (missing.Count > 0)
                {
                    failures.Add($"link {link["id"]} lacks {missing.Count} evidence of its {(side == link["from"] ? "from" : "to")} side");
                }
            }
        }

        foreach (var secret in expected["secretsAbsent"]?.AsArray().Select(s => (string)s!) ?? [])
        {
            foreach (var file in Directory.EnumerateFiles(output, "*", SearchOption.AllDirectories))
            {
                if (File.ReadAllText(file).Contains(secret, StringComparison.Ordinal))
                {
                    failures.Add($"secret value found in {Path.GetRelativePath(output, file)}");
                }
            }
        }
        return failures;
    }

    /// <summary>"proj|docid" is shorthand for "dotnet:proj:docid".</summary>
    private static string Id(string text) => text.Contains('|') ? "dotnet:" + text.Replace("|", ":", StringComparison.Ordinal) : text;

    /// <summary>"kind from -> to [usage=u] [@path:line,path:line]" with shorthand ids.</summary>
    private static string Relation(string text, bool withLines)
    {
        var match = RelationPattern().Match(text.Trim());
        if (!match.Success)
        {
            throw new FormatException($"Bad relation line '{text}'.");
        }
        var usage = match.Groups["usage"].Success ? $" usage={match.Groups["usage"].Value}" : string.Empty;
        var lines = withLines ? " @" + string.Join(",", match.Groups["at"].Value.Split(',', StringSplitOptions.RemoveEmptyEntries).Order(StringComparer.Ordinal)) : string.Empty;
        return $"{match.Groups["kind"].Value} {Id(match.Groups["from"].Value)} -> {Id(match.Groups["to"].Value)}{usage}{lines}";
    }

    private static bool Matches(JsonObject expected, JsonObject actual, List<string> lines)
    {
        foreach (var (key, value) in expected)
        {
            if (key == "at")
            {
                if (!lines.Contains((string)value!))
                {
                    return false;
                }
                continue;
            }
            if (!actual.TryGetPropertyValue(key, out var actualValue))
            {
                return false;
            }
            if (value is JsonObject nested)
            {
                if (actualValue is not JsonObject actualNested || !Matches(nested, actualNested, lines))
                {
                    return false;
                }
                continue;
            }
            var expectedText = value is null ? "null" : Id((string)value!);
            var actualText = actualValue switch
            {
                null => "null",
                JsonValue v when v.TryGetValue(out string? s) => s,
                JsonValue v when v.TryGetValue(out bool b) => b ? "true" : "false",
                _ => actualValue.ToJsonString(),
            };
            if (expectedText != actualText)
            {
                return false;
            }
        }
        return true;
    }

    /// <summary>Scalars as text (booleans lower-case), arrays as "[a,b]", null as "null"; expected.yml scalars are strings.</summary>
    private static string Text(JsonNode? node) => node switch
    {
        null => "null",
        JsonArray array => "[" + string.Join(",", array.Select(Text)) + "]",
        JsonValue v when v.TryGetValue(out string? s) => s,
        JsonValue v when v.TryGetValue(out bool b) => b ? "true" : "false",
        _ => node.ToJsonString(),
    };

    private static string Describe(JsonObject observation)
    {
        var copy = (JsonObject)observation.DeepClone();
        foreach (var key in new[] { "id", "evidence", "context", "project" })
        {
            copy.Remove(key);
        }
        return copy.ToJsonString();
    }

    private static void Check(List<string> failures, string what, string? expected, string? actual)
    {
        if (expected is not null && expected != actual)
        {
            failures.Add($"{what} '{actual}', expected '{expected}'");
        }
    }

    private static void CompareSets(List<string> failures, string what, IEnumerable<string> expected, IEnumerable<string> actual)
    {
        var e = expected.ToHashSet(StringComparer.Ordinal);
        var a = actual.ToHashSet(StringComparer.Ordinal);
        failures.AddRange(e.Except(a).Order(StringComparer.Ordinal).Select(x => $"{what}: missing {x}"));
        failures.AddRange(a.Except(e).Order(StringComparer.Ordinal).Select(x => $"{what}: unexpected {x}"));
    }

    private static List<JsonObject> Read(string output, string file) =>
        File.ReadLines(Path.Combine(output, file)).Select(l => JsonNode.Parse(l)!.AsObject()).ToList();

    [GeneratedRegex(@"^(?<kind>\S+)\s+(?<from>\S+)\s+->\s+(?<to>\S+)(?:\s+usage=(?<usage>\S+))?(?:\s+@(?<at>\S+))?$")]
    private static partial Regex RelationPattern();
}
